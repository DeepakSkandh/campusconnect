/** ISO timestamp for `days` from today at `hour:minute` India time (UTC+05:30). */
function at(days: number, hour: number, minute = 0): string {
  const now = new Date();
  return new Date(
    Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate() + days, hour - 5, minute - 30),
  ).toISOString();
}

